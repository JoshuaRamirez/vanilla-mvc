async function guide() {
  const { agentGuide } = await import('../architecture/guide.mjs');
  const out = resolve(CWD, value('out', 'AGENTS.md'));
  const name = JSON.parse(await readFile(join(CWD, 'package.json'), 'utf8').catch(() => '{}')).name ?? 'this application';
  const text = agentGuide({ name });
  if (flag('check')) {
    const onDisk = await readFile(out, 'utf8').catch(() => null);
    if (onDisk === text) return console.log(`${out} matches the installed framework.`);
    die(`${out} is ${onDisk === null ? 'missing' : 'stale'}: run \`vanilla-mvc guide\`.`);
  }
  await writeFile(out, text);
  console.log(`wrote ${out}`);
}


// ---- check -------------------------------------------------------------------------------------

/** The layout init writes. An application laid out otherwise runs applicationRules itself. */
const LAYOUT = {
  root: 'src',
  app: 'src/',
  within: ['vanilla-mvc', 'src/'],
  libraries: 'vanilla-mvc/',
  styling: { folder: 'vanilla-mvc/css', from: /\.(template|style)\.ts$/ },
  events: ['src/events'],
  // Floors guard against a rule that silently stopped matching: that is the test suite's job.
  // Judging one edit, only what the edit broke matters.
  atLeast: { models: 0, events: 0, controllers: 0, handlers: 0, waits: 0, calls: 0, tags: 0 },
};

/** The nearest directory at or above `from` holding a package.json that depends on vanilla-mvc. */
async function appRoot(from) {
  for (let dir = resolve(from); ; dir = dirname(dir)) {
    const pkg = JSON.parse(await readFile(join(dir, 'package.json'), 'utf8').catch(() => 'null'));
    if (pkg && (pkg.dependencies?.['vanilla-mvc'] || pkg.devDependencies?.['vanilla-mvc'])) return dir;
    if (dirname(dir) === dir) return null;
  }
}

/** Run every rule over `base`; give back each broken rule with the first line of what it said. */
async function broken(base) {
  const { applicationRules, RULES } = await import('../architecture/rules.mjs');
  const { default: assert } = await import('node:assert/strict');
  const out = [];
  let index = 0;
  applicationRules({
    ...LAYOUT,
    base,
    assert,
    test: (_name, fn) => {
      const rule = RULES[index++];
      try {
        fn();
      } catch (error) {
        out.push({ rule, message: String(error.message) });
      }
    },
  });
  return out;
}

/** A line to $TMPDIR/vanilla-mvc-check.log per firing: a hook silent when idle looks like one that never ran. */
async function logLine(text) {
  const { appendFile } = await import('node:fs/promises');
  const { tmpdir } = await import('node:os');
  await appendFile(join(tmpdir(), 'vanilla-mvc-check.log'), `${new Date().toISOString()} ${text}\n`).catch(() => {});
}

/**
 * Judge an edit against the rules, while the edit is still the last thing that happened.
 *
 *   vanilla-mvc check [file…]   print what the files break (every rule, if none are named); exit 1
 *   vanilla-mvc check --hook    read a Claude Code PostToolUse payload on stdin; exit 2 with the
 *                               verdict on stderr, which Claude Code hands back to the agent
 *
 * Only rules the edited file is named in are reported: a debt elsewhere is not this edit's.
 */
async function check() {
  let files = positional;
  let from = CWD;
  if (flag('hook')) {
    let raw = '';
    for await (const chunk of process.stdin) raw += chunk;
    const payload = JSON.parse(raw || '{}');
    const file = payload.tool_input?.file_path ?? payload.tool_input?.path;
    if (!file || !/\.ts$/.test(file)) {
      await logLine(`skip ${file ?? '(no file)'}: not TypeScript`);
      return;
    }
    files = [file];
    from = dirname(resolve(payload.cwd ?? CWD, file));
  }
  const base = await appRoot(files[0] ? dirname(resolve(CWD, files[0])) : from);
  if (!base) {
    await logLine(`skip ${files[0] ?? from}: no application on vanilla-mvc above it`);
    if (flag('hook')) return;
    die('vanilla-mvc check: no package.json depending on vanilla-mvc at or above here.');
  }
  const named = files.map((f) => relative(base, resolve(CWD, f)).split(sep).join('/'));
  if (named.some((f) => f.startsWith('..') || !f.startsWith('src/'))) {
    await logLine(`skip ${named.join(', ')}: outside src/`);
    if (flag('hook')) return;
  }

  const all = await broken(base);
  const mine = named.length ? all.filter((b) => named.some((f) => b.message.includes(f))) : all;
  await logLine(`${named.join(', ') || base}: ${mine.length} broken of ${all.length} red`);
  if (mine.length === 0) {
    if (!flag('hook')) console.log(`${named.join(', ') || base}: every rule holds.`);
    return;
  }

  const report = [
    `vanilla-mvc: ${named.join(', ') || 'this application'} breaks ${mine.length} architecture rule${mine.length === 1 ? '' : 's'}.`,
    ...mine.map(({ rule, message }) => {
      const where = message.split('\n').filter((l) => named.some((f) => l.includes(f))).map((l) => l.trim().replace(/^[+-]\s*/, '')).slice(0, 3);
      return [`- ${rule.says}`, `  why: ${rule.why}`, ...where.map((w) => `  at: ${w}`), `  right:\n${rule.right.replace(/^/gm, '      ')}`].join('\n');
    }),
    'Fix it now, before the next edit. Every rule with a wrong and a right example: npx vanilla-mvc rules',
  ].join('\n');
  process.stderr.write(`${report}\n`);
  process.exit(flag('hook') ? 2 : 1);
}

