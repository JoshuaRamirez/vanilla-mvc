#!/usr/bin/env node
// The three jobs every application built on this framework has to do, so that none of them has to
// be rewritten per application. Each was hand-carried into the first consumer before it lived here.
//
//   vanilla-mvc init [dir]        a new application: manifest, tsconfig, shell, import map
//   vanilla-mvc vendor [--check]  copy the framework's compiled tree to ./vendor for the browser
//   vanilla-mvc theme-css [--check]  write the theme's tokens as a plain stylesheet
//
// Run `vanilla-mvc <command> --help` for a command's own options.
import { cp, mkdir, readFile, readdir, rm, stat, writeFile } from 'node:fs/promises';
import { createRequire } from 'node:module';
import { dirname, join, relative, resolve, sep } from 'node:path';

const [command, ...rest] = process.argv.slice(2);
const flag = (name) => rest.includes(`--${name}`);
const value = (name, fallback) => {
  const at = rest.indexOf(`--${name}`);
  return at === -1 ? fallback : rest[at + 1];
};
const OPTIONS_WITH_VALUES = new Set(['out', 'accent', 'name', 'registry']);
/** Bare arguments: not a flag, and not the value of one. */
const positional = rest.filter((a, i) => !a.startsWith('--') && !(i > 0 && rest[i - 1].startsWith('--') && OPTIONS_WITH_VALUES.has(rest[i - 1].slice(2))));

const die = (message) => { console.error(message); process.exit(1); };
const CWD = process.cwd();

/** The installed framework: where its package.json is, and what version. */
async function framework(from = CWD) {
  const require = createRequire(join(from, 'x.mjs'));
  let manifest;
  try {
    manifest = require.resolve('vanilla-mvc/package.json');
  } catch {
    die(`vanilla-mvc is not installed in ${from}.\n  npm install vanilla-mvc`);
  }
  return { dir: dirname(manifest), pkg: JSON.parse(await readFile(manifest, 'utf8')) };
}

// ---- vendor ----------------------------------------------------------------------------------

/**
 * A browser cannot resolve the bare name `vanilla-mvc`, so index.html carries an import map that
 * points at /vendor, and this puts the framework there. A copy rather than a symlink: a build that
 * stages the site elsewhere — into a container, into a compiled binary — would not follow one.
 */
async function vendor() {
  const out = resolve(CWD, value('out', 'vendor'));
  const { dir, pkg } = await framework();
  const from = join(dir, 'dist');
  const stamp = join(out, '.version');
  const installed = `${pkg.name}@${pkg.version}\n`;
  const current = await readFile(stamp, 'utf8').catch(() => null);

  if (flag('check')) {
    if (current === installed) return console.log(`${out} is ${installed.trim()}`);
    die(`${out} holds ${current?.trim() ?? 'nothing'} but node_modules holds ${installed.trim()}.\n  npx vanilla-mvc vendor`);
  }
  await stat(from).catch(() => die(`${from} does not exist: the installed vanilla-mvc has no compiled tree.`));
  await rm(out, { recursive: true, force: true });
  await cp(from, out, { recursive: true });
  await writeFile(stamp, installed);
  console.log(`${out} <- ${installed.trim()}`);
}

// ---- theme-css -------------------------------------------------------------------------------

/**
 * The document sheet is the live one, applied through the styling seam at start. But a module
 * bundle is fetched, parsed and executed before any of that, and until it is the page has a reset
 * and nothing else: white on white, a flash on every cold load. So the same engine emits the same
 * tokens twice, by two paths — here through the *Text forms, which return CSS as a string because
 * there is no `css` tag out here and nothing to bind. One home for the values either way.
 */
async function themeCss() {
  const { dir } = await framework();
  const engine = await import(new URL('dist/libraries/css/theme/index.js', `file://${dir}/`).href);
  const out = resolve(CWD, value('out', 'theme.css'));
  const accents = rest.flatMap((a, i) => (a === '--accent' ? [rest[i + 1]] : []));

  const css = [
    '/* Generated by `vanilla-mvc theme-css`. Do not edit: run the command.',
    '   The same tokens the document sheet applies at start, as a file, so the first paint has them. */',
    engine.themeText(),
    engine.modesText(),
    engine.scalesText(),
    ...accents.map((selector) => engine.paletteText('accent', { selector })),
  ].join('\n');

  if (flag('check')) {
    const onDisk = await readFile(out, 'utf8').catch(() => null);
    if (onDisk === css) return console.log(`${out} matches the engine.`);
    die(`${out} is ${onDisk === null ? 'missing' : 'stale'}: run \`vanilla-mvc theme-css${accents.map((a) => ` --accent ${a}`).join('')}\`.`);
  }
  await writeFile(out, css);
  console.log(`wrote ${out} (${css.split('\n').length} lines)`);
}

// ---- init ------------------------------------------------------------------------------------

const ENTRIES = ['', '/css', '/fields', '/router', '/templates'];
const importMap = (indent) => {
  const line = (entry) => {
    const to = entry === '' ? '/vendor/framework/index.js' : `/vendor/libraries/${entry.slice(1)}/index.js`;
    return `${indent}    "vanilla-mvc${entry}": "${to}"`;
  };
  return [`${indent}{`, `${indent}  "imports": {`, [...ENTRIES.map(line), `${indent}    "vanilla-mvc/dist/": "/vendor/"`].join(',\n'), `${indent}  }`, `${indent}}`].join('\n');
};

async function init() {
  const dir = resolve(CWD, positional[0] ?? '.');
  const name = value('name', dir.split('/').pop());
  const existing = await readdir(dir).catch(() => []);
  if (existing.some((e) => ['src', 'index.html', 'tsconfig.json'].includes(e))) {
    die(`${dir} already has an application in it (src/, index.html or tsconfig.json). Pick an empty directory.`);
  }
  const { pkg } = await framework(dir).catch(() => ({ pkg: { version: '*' } }));
  // However this framework was installed — a registry, a tag, a git URL — keep that spec: an
  // application that fetched it from GitHub must not end up depending on a version npm cannot find.
  const installed = JSON.parse(await readFile(join(dir, 'package.json'), 'utf8').catch(() => '{}'));
  const spec = installed.dependencies?.['vanilla-mvc'] ?? installed.devDependencies?.['vanilla-mvc'] ?? `^${pkg.version}`;
  const write = async (path, body) => {
    await mkdir(dirname(join(dir, path)), { recursive: true });
    await writeFile(join(dir, path), body);
    console.log(`  ${path}`);
  };

  console.log(`Creating ${name} in ${dir}`);
  await write('package.json', JSON.stringify({
    name, version: '0.1.0', type: 'module', private: true,
    scripts: {
      vendor: 'vanilla-mvc vendor',
      'theme:css': 'vanilla-mvc theme-css',
      build: 'npm run vendor && tsc',
      watch: 'tsc --watch',
      start: 'npm run build && node server.mjs',
      typecheck: 'tsc --noEmit',
      test: 'tsc --noEmit && vanilla-mvc guide --check && node --test test/*.test.mjs',
      guide: 'vanilla-mvc guide',
    },
    dependencies: { 'vanilla-mvc': spec },
    // typescript5 is TypeScript 5's parser under another name: vanilla-mvc/architecture reads
    // your source with it. TypeScript 7 compiles; 5 only parses, because its parser is the stable API.
    devDependencies: { typescript: '^7.0.2', '@types/node': '^22.20.3', typescript5: 'npm:typescript@~5.9.3' },
  }, null, 2) + '\n');

  // Only when asked: an application installing vanilla-mvc from a private or local registry.
  const registry = value('registry', null);
  if (registry) await write('.npmrc', `registry=${registry.replace(/\/?$/, '/')}\n`);

  await write('tsconfig.json', JSON.stringify({
    compilerOptions: {
      target: 'ES2022', module: 'ESNext', moduleResolution: 'Bundler',
      lib: ['ES2022', 'DOM', 'DOM.Iterable'],
      strict: true, noImplicitOverride: true,
      rootDir: 'src', outDir: 'dist',
      // declaration: the .d.ts beside each .js is what a checkJs test pass reads. Without it,
      // `tsc --checkJs` over your tests type-checks the emitted JavaScript instead, and reports
      // hundreds of errors about your own compiled output.
      declaration: true, sourceMap: true,
      types: [], rewriteRelativeImportExtensions: true,
    },
    include: ['src'],
  }, null, 2) + '\n');

  await write('.gitignore', 'node_modules/\ndist/\nvendor/\n.DS_Store\n');

  // What an agent reads before it writes code here, generated from the rules the tests enforce.
  const { agentGuide } = await import('../architecture/guide.mjs');
  await write('AGENTS.md', agentGuide({ name }));
  // Claude Code reads CLAUDE.md; one line imports the same guide, so there is one text, not two.
  await write('CLAUDE.md', '@AGENTS.md\n');

  // After every edit an agent makes, judge the file against the rules and hand any breakage back
  // while that edit is still the last thing it did. A command hook, because it must reach the
  // agent's context; PostToolUse, where exit 2 is feedback rather than a veto. It cds itself: the
  // project directory variable is not always set, and a hook that runs in the wrong place says
  // nothing.
  await write('.claude/settings.json', JSON.stringify({
    hooks: {
      PostToolUse: [{
        matcher: 'Edit|Write|MultiEdit',
        hooks: [{
          type: 'command',
          command: 'cd "${CLAUDE_PROJECT_DIR:-.}" && node node_modules/vanilla-mvc/bin/vanilla-mvc.mjs check --hook',
          timeout: 30,
        }],
      }],
    },
  }, null, 2) + '\n');

  await write('test/architecture.test.mjs', `// This application's architecture, checked by vanilla-mvc's own rules on the syntax tree.
// \`npx vanilla-mvc rules\` prints each with its reason and a wrong and right example.
//
// \`atLeast\` is a floor per rule, counted on src/ as it stands. Raise it as the application grows,
// never lower it: a rule that finds nothing to check is a rule that is not running.
import { test } from 'node:test';
import assert from 'node:assert/strict';
import { applicationRules } from 'vanilla-mvc/architecture';

applicationRules({
  test,
  assert,
  base: new URL('..', import.meta.url).pathname,
  root: 'src',
  app: 'src/',
  within: ['vanilla-mvc', 'src/'],
  styling: { folder: 'vanilla-mvc/css', from: /\\.(template|style)\\.ts$/ },
  events: ['src/events'],
  atLeast: { models: 1, events: 1, controllers: 1, handlers: 1, waits: 0, calls: 0, tags: 0 },
});
`);

  await write('index.html', `<!doctype html>
<html lang="en">
  <head>
    <meta charset="utf-8" />
    <meta name="viewport" content="width=device-width, initial-scale=1" />
    <title>${name}</title>
    <link rel="stylesheet" href="/styles.css" />
    <!-- Generated by \`npm run theme:css\`: the theme's tokens as a plain file, so the first
         paint has them before the module bundle is fetched. Delete both if you don't want it. -->
    <link rel="stylesheet" href="/theme.css" />
    <!-- The source says \`import … from 'vanilla-mvc'\`. A browser cannot resolve a bare name, so
         this says where it lives: /vendor, a copy of the installed package's compiled tree made
         by \`npm run vendor\` on every build. -->
    <script type="importmap">
${importMap('      ')}
    </script>
    <script type="module" src="/dist/main.js"></script>
  </head>
  <body>
    <div id="app"></div>
  </body>
</html>
`);

  await write('styles.css', `/* A reset only. Colour, spacing and type come from the document sheet (src/document.style.ts). */
*, *::before, *::after { box-sizing: border-box; }
body { margin: 0; }
h1, h2, h3, p, ul, ol, figure { margin: 0; }
button, input, select, textarea { font: inherit; color: inherit; }
button { cursor: pointer; }
button:disabled { cursor: default; }
textarea { width: 100%; }
main, header, aside { display: block; }
`);

  await write('server.mjs', `// A dev server: static files with SPA fallback. The site is a named list, not "any file under
// the root" — the root is the repository root, and package.json is not the site.
import { createServer } from 'node:http';
import { readFile } from 'node:fs/promises';
import { extname, join, normalize, sep } from 'node:path';

const PORT = Number(process.env.PORT ?? 4500);
const ROOT = import.meta.dirname;
const SITE = ['/styles.css', '/theme.css', '/index.html'];
const SITE_DIRS = ['/dist/', '/vendor/'];
const TYPES = { '.html': 'text/html', '.js': 'text/javascript', '.css': 'text/css', '.map': 'application/json', '.svg': 'image/svg+xml' };

const server = createServer(async (req, res) => {
  const path = normalize(new URL(req.url ?? '/', 'http://localhost').pathname);
  const onSite = SITE.includes(path) || SITE_DIRS.some((dir) => path.startsWith(dir));
  const file = normalize(join(ROOT, path));
  const isAsset = onSite && file.startsWith(ROOT + sep) && extname(file) !== '';
  try {
    if (!isAsset && extname(path) !== '') {
      res.writeHead(404, { 'content-type': 'application/json' });
      return res.end(JSON.stringify({ error: 'Not found.' }));
    }
    const body = await readFile(isAsset ? file : join(ROOT, 'index.html'));
    res.writeHead(200, { 'content-type': TYPES[isAsset ? extname(file) : '.html'] ?? 'application/octet-stream' });
    res.end(body);
  } catch {
    res.writeHead(404, { 'content-type': 'application/json' });
    res.end(JSON.stringify({ error: 'Not found.' }));
  }
});

server.listen(PORT, () => console.log(\`http://localhost:\${server.address().port}\`));
`);

  await write('src/events/ticks-changed.ts', `/** A fact, as plain frozen data. One event per file, and it names itself. */
export interface TicksChanged {
  type: 'TicksChanged';
  ticks: number;
}
`);

  await write('src/application/counter.ts', `import { ApplicationElement } from 'vanilla-mvc';
import type { TicksChanged } from '../events/ticks-changed.ts';

/**
 * One capability of the application: what it knows, and what it does when asked. It owns the
 * number; no screen does. When it changes, it publishes the fact and whoever cares hears it.
 */
export class Counter extends ApplicationElement {
  #ticks = 0;

  increment(): void {
    this.#ticks += 1;
    this.publish<TicksChanged>({ type: 'TicksChanged', ticks: this.#ticks });
  }
}
`);

  await write('src/application/application-domain.ts', `import { ApplicationElement } from 'vanilla-mvc';
import { Counter } from './counter.ts';

/**
 * What the application knows and does, apart from any screen. Capabilities are children: each is
 * an ApplicationElement of its own, and a controller reaches one through \`this.domain\`.
 */
export class ApplicationDomain extends ApplicationElement {
  counter!: Counter;

  /**
   * adopt() sets the child's parent and puts it in the tree, so it goes through create,
   * interconnect and activate with the domain. Pushing to \`children\` yourself skips the parent,
   * and the child then fails at its first publish with "not attached to an application".
   */
  protected override onCreate(): void {
    this.counter = this.adopt(new Counter());
  }
}
`);

  await write('src/components/home-page/home-page.model.ts', `/** What the view reads. Data only: no methods, no behaviour. */
export interface HomePageModel {
  greeting: string;
  ticks: number;
}
`);

  await write('src/components/home-page/home-page.controller.ts', `import { Controller } from 'vanilla-mvc';
import type { ApplicationDomain } from '../../application/application-domain.ts';
import type { TicksChanged } from '../../events/ticks-changed.ts';
import type { HomePageModel } from './home-page.model.ts';

export class HomePageController extends Controller<HomePageModel, ApplicationDomain> {
  protected createModel(): HomePageModel {
    return { greeting: 'Hello', ticks: 0 };
  }

  /**
   * Every DOM handler is registered here and bound by name in the template. It has to be: the
   * change engine draws at the end of a DOM event it delivered, and an inline arrow is not one.
   * Write \`@click=\${c.handler('tick')}\`, never \`@click=\${() => c.tick()}\`.
   */
  protected override onInterconnect(): void {
    this.handle('tick', this.#tick);
    this.subscribe<TicksChanged>('TicksChanged', this.#ticksChanged);
  }

  /** A gesture goes to the application domain. It changes nothing here — that is the next method. */
  #tick(): void {
    this.domain.counter.increment();
  }

  /** A fact arrives: map it onto the model, then say so. changed() states; it does not render. */
  #ticksChanged({ ticks }: TicksChanged): void {
    this.model.ticks = ticks;
    this.changed();
  }
}
`);

  await write('src/components/home-page/home-page.template.ts', `import { html, Template } from 'vanilla-mvc';
import type { HomePageController } from './home-page.controller.ts';
import type { HomePageModel } from './home-page.model.ts';

export const homePageTemplate = new Template<HomePageModel, HomePageController>(
  (m, c) => html\`
    <section class="home">
      <h1>\${m.greeting}</h1>
      <button @click=\${c.handler('tick')}>ticks: \${m.ticks}</button>
    </section>
  \`,
);
`);

  await write('src/components/home-page/home-page.component.ts', `import { Component } from 'vanilla-mvc';
import { HomePageController } from './home-page.controller.ts';
import type { HomePageModel } from './home-page.model.ts';
import { homePageTemplate } from './home-page.template.ts';

export class HomePageComponent extends Component<HomePageModel, HomePageController> {
  protected createTemplate() { return homePageTemplate; }
  protected createController() { return new HomePageController(); }
  // protected override createChildren() { return [new OtherComponent('other')]; }
}
`);

  await write('src/app.ts', `import { Application, type Component } from 'vanilla-mvc';
import { ApplicationDomain } from './application/application-domain.ts';
import { HomePageComponent } from './components/home-page/home-page.component.ts';

/** The root: the bus, the application domain, the router and the shell. */
export class ${name.replace(/(^|[-_])(\w)/g, (_, __, c) => c.toUpperCase())}Application extends Application<ApplicationDomain> {
  protected createDomain(): ApplicationDomain { return new ApplicationDomain(); }
  protected createShell(): Component { return new HomePageComponent('home-page'); }
  // protected override createRoutes(): IRouteTable { return routes; }
}
`);

  await write('src/main.ts', `import { ${name.replace(/(^|[-_])(\w)/g, (_, __, c) => c.toUpperCase())}Application } from './app.ts';

// start() = create() -> interconnect() -> activate() -> render()
const app = new ${name.replace(/(^|[-_])(\w)/g, (_, __, c) => c.toUpperCase())}Application(document.getElementById('app')!).start();

// For poking at from the console.
Object.assign(window, { app });
`);

  console.log(`
Next:
  cd ${dir === CWD ? '.' : dir}
  npm install
  npm run theme:css
  npm start          # http://localhost:4500
  npm test           # the architecture rules, and that AGENTS.md matches the installed framework`);
}


// ---- add ---------------------------------------------------------------------------------------

/** 'todo-list', 'TodoList' or 'todoList' → { kebab: 'todo-list', pascal: 'TodoList', camel: 'todoList' }. */
function names(raw) {
  if (!raw || !/^[A-Za-z][A-Za-z0-9-]*$/.test(raw)) die(`vanilla-mvc add: "${raw ?? ''}" is not a name. Use letters, digits and dashes: todo-list, TodoList.`);
  const kebab = raw.replace(/([a-z0-9])([A-Z])/g, '$1-$2').toLowerCase();
  const pascal = kebab.replace(/(^|-)(\w)/g, (_, __, c) => c.toUpperCase());
  return { kebab, pascal, camel: pascal[0].toLowerCase() + pascal.slice(1) };
}

/** Write each file, refusing to touch one that exists: a generator that overwrites is a generator nobody runs twice. */
async function writeNew(files) {
  for (const path of Object.keys(files)) {
    if (await stat(join(CWD, path)).then(() => true, () => false)) die(`vanilla-mvc add: ${path} already exists. Nothing was written.`);
  }
  for (const [path, body] of Object.entries(files)) {
    await mkdir(dirname(join(CWD, path)), { recursive: true });
    await writeFile(join(CWD, path), body);
    console.log(`  ${path}`);
  }
}

/**
 * A component: model, controller, template, component, and a style unless --no-style. The shape
 * every rule in vanilla-mvc/architecture expects — a model that is only an interface, a controller
 * with nothing public, the css tag inside the Style callback.
 */
function componentFiles({ kebab, pascal }, style) {
  const dir = `src/components/${kebab}`;
  const files = {
    [`${dir}/${kebab}.model.ts`]: `/** What the ${kebab} view reads. Types only: no values, no behaviour. */
export interface ${pascal}Model {
  title: string;
}
`,
    [`${dir}/${kebab}.controller.ts`]: `import { Controller } from 'vanilla-mvc';
import type { ApplicationDomain } from '../../application/application-domain.ts';
import type { ${pascal}Model } from './${kebab}.model.ts';

/**
 * Maps gestures to the application domain, and facts from it onto the model.
 *
 * A DOM handler is registered in onInterconnect and bound by name:
 *   this.handle('save', this.#save);         template: @click=\${c.handler('save')}
 * A fact is subscribed to the same way, and states what it changed:
 *   this.subscribe<Saved>('Saved', this.#saved);
 *   #saved({ title }: Saved): void { this.model.title = title; this.changed(); }
 * A handler never writes the model itself: it calls the domain, and the fact comes back.
 */
export class ${pascal}Controller extends Controller<${pascal}Model, ApplicationDomain> {
  protected createModel(): ${pascal}Model {
    return { title: '${pascal}' };
  }
}
`,
    [`${dir}/${kebab}.template.ts`]: `import { html, ${style ? 'styled, ' : ''}Template } from 'vanilla-mvc';
import type { ${pascal}Controller } from './${kebab}.controller.ts';
import type { ${pascal}Model } from './${kebab}.model.ts';
${style ? `import { ${style} } from './${kebab}.style.ts';\n` : ''}
/** One root element. Bind events as @click=\${c.handler('name')}, never an inline arrow. */
export const ${pascal[0].toLowerCase() + pascal.slice(1)}Template = new Template<${pascal}Model, ${pascal}Controller>(
  (m, c) => html\`
    <section class="${kebab}"${style ? ` \${styled(${style}, m)}` : ''}>
      <h2>\${m.title}</h2>
    </section>
  \`,
);
`,
    [`${dir}/${kebab}.component.ts`]: `import { Component } from 'vanilla-mvc';
import { ${pascal}Controller } from './${kebab}.controller.ts';
import type { ${pascal}Model } from './${kebab}.model.ts';
import { ${pascal[0].toLowerCase() + pascal.slice(1)}Template } from './${kebab}.template.ts';

export class ${pascal}Component extends Component<${pascal}Model, ${pascal}Controller> {
  protected createTemplate() { return ${pascal[0].toLowerCase() + pascal.slice(1)}Template; }
  protected createController() { return new ${pascal}Controller(); }
}
`,
  };
  if (style) {
    files[`${dir}/${kebab}.style.ts`] = `import { css, Style } from 'vanilla-mvc';
import { layout } from 'vanilla-mvc/css';
import type { ${pascal}Model } from './${kebab}.model.ts';

/** The css tag lives inside this callback: at module scope it runs before the adapters exist. */
export const ${style} = new Style<${pascal}Model>(
  () => css\`
    :scope {
      \${layout.stack({ gap: '2' })}
    }
  \`,
);
`;
  }
  return files;
}

async function add() {
  const [kind, raw] = positional;
  if (!['component', 'event', 'capability'].includes(kind)) die('vanilla-mvc add component|event|capability <name>');
  const n = names(raw);

  if (kind === 'component') {
    const style = flag('no-style') ? null : `${n.camel}Style`;
    await writeNew(componentFiles(n, style));
    console.log(`
Now give it a place. In the parent component:
  createChildren() { return [..., new ${n.pascal}Component('${n.kebab}')]; }
and in the parent's template:
  <div data-component="${n.kebab}"></div>`);
  } else if (kind === 'event') {
    await writeNew({
      [`src/events/${n.kebab}.ts`]: `/** A fact, as plain frozen data. One event per file; its type is its own name. */
export interface ${n.pascal} {
  readonly type: '${n.pascal}';
}
`,
    });
    console.log(`
Publish it from a capability:  this.publish<${n.pascal}>({ type: '${n.pascal}' });
Hear it in a controller:       this.subscribe<${n.pascal}>('${n.pascal}', this.#${n.camel});`);
  } else {
    await writeNew({
      [`src/application/${n.kebab}.ts`]: `import { ApplicationElement } from 'vanilla-mvc';

/**
 * One capability of the application: what it knows, and what it does when asked. It owns its
 * state; no screen does. When that changes it publishes a fact (an event under src/events), and
 * whoever cares hears it. Work that waits hands back its promise: \`load(): Promise<void>\`.
 */
export class ${n.pascal} extends ApplicationElement {}
`,
    });
    console.log(`
Adopt it in ApplicationDomain:
  ${n.camel}!: ${n.pascal};
  protected override onCreate(): void { this.${n.camel} = this.adopt(new ${n.pascal}()); }`);
  }
}


